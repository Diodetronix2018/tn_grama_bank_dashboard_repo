"""Build a single self-contained HTML file from the source tree.

Mail systems routinely block .js attachments, even inside a .zip, so the
easiest way to send someone a working copy of the dashboard is one .html file
they can double-click. This inlines the stylesheet, the logo and every script in the
order index.html loads them.

    python build/bundle.py

Writes dist/tngb-dashboard-standalone.html. Run it from the project root.
"""

import base64
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "dist" / "tngb-dashboard-standalone.html"

# A literal </script> inside inlined code would end the tag early. None of the
# sources contain one today; fail loudly rather than emit a broken file.
CLOSING_TAG = re.compile(r"</\s*script", re.IGNORECASE)

# Images the page references by path; each becomes an inline data: URI.
IMAGES = ["assets/logo.png"]


def read(relative):
    path = ROOT / relative
    if not path.exists():
        sys.exit("missing source file: %s" % relative)
    return path.read_text(encoding="utf-8")


def script_sources(index_html):
    """The script paths from index.html, in load order."""
    return re.findall(r'<script src="([^"]+)"></script>', index_html)


def main():
    index_html = read("index.html")
    css = read("assets/styles.css")
    scripts = script_sources(index_html)
    if not scripts:
        sys.exit("no <script src> tags found in index.html")

    parts = []
    for relative in scripts:
        code = read(relative)
        if CLOSING_TAG.search(code):
            sys.exit("%s contains a literal </script> and cannot be inlined" % relative)
        parts.append("/* ==== %s ==== */\n%s" % (relative, code))

    head_end = index_html.index("</head>")
    head = index_html[:head_end]

    # Drop the external stylesheet link; its contents go inline instead.
    head = re.sub(r'\n?<link rel="stylesheet" href="assets/styles\.css">', "", head)

    for relative in IMAGES:
        path = ROOT / relative
        if not path.exists():
            sys.exit("missing image: %s" % relative)
        uri = "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode("ascii")
        head = head.replace(relative, uri)
        parts = [p.replace(relative, uri) for p in parts]

    html = "".join([
        head,
        "<style>\n", css, "\n</style>\n",
        "</head>\n<body>\n\n",
        '<div id="app"></div>\n\n',
        "<!-- Single-file build. Generated by build/bundle.py from the source\n",
        "     tree; edit the files under src/ and rebuild, not this file. -->\n",
        "<script>\n", "\n".join(parts), "\n</script>\n",
        "</body>\n</html>\n",
    ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding="utf-8")
    print("wrote %s (%.0f KB from %d scripts)" % (OUT, len(html.encode("utf-8")) / 1024, len(scripts)))


if __name__ == "__main__":
    main()
